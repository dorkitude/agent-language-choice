	mux.HandleFunc("POST /v1/play/campaigns/{id}/encounters/{enc_id}/damage", damagePlayCampaignEncounterCombatant)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/encounters/{enc_id}/heal", healPlayCampaignEncounterCombatant)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/encounters/{enc_id}/rewards", awardPlayCampaignEncounterRewards)
