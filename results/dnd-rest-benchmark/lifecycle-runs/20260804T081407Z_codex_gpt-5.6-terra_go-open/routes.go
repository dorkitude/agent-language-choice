	mux.HandleFunc("POST /v1/play/campaigns/{id}/characters/{char_id}/death-saves", recordPlayCampaignDeathSave)
	mux.HandleFunc("GET /v1/play/campaigns/{id}/characters/{char_id}/status", getPlayCampaignCharacterStatus)
