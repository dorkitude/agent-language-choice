	mux.HandleFunc("POST /v1/dice/stats", diceStats)
	mux.HandleFunc("POST /v1/checks/ability", abilityCheck)
	mux.HandleFunc("POST /v1/encounters/adjusted-xp", adjustedXP)
	mux.HandleFunc("POST /v1/initiative/order", initiativeOrder)
