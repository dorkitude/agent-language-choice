	mux.HandleFunc("POST /v1/combat/sessions/{id}/conditions", addCondition)
	mux.HandleFunc("POST /v1/combat/sessions/{id}/advance", advanceTurn)
	mux.HandleFunc("POST /v1/auth/register", registerUser)
	mux.HandleFunc("POST /v1/auth/login", loginUser)
	mux.HandleFunc("POST /v1/play/campaigns", createPlayCampaign)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/members", joinPlayCampaign)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/start", startPlayCampaign)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/encounters", createPlayCampaignEncounter)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/encounters/{enc_id}/monsters", addPlayCampaignEncounterMonster)
	mux.HandleFunc("DELETE /v1/play/campaigns/{id}/encounters/{enc_id}/monsters/{monster_id}", removePlayCampaignEncounterMonster)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/encounters/{enc_id}/combatants", addPlayCampaignEncounterCombatant)
	mux.HandleFunc("DELETE /v1/play/campaigns/{id}/encounters/{enc_id}/combatants/{member}", removePlayCampaignEncounterCombatant)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/encounters/{enc_id}/conditions", addPlayCampaignEncounterCondition)
	mux.HandleFunc("GET /v1/play/campaigns/{id}/encounters/{enc_id}/status", getPlayCampaignEncounterStatus)
	mux.HandleFunc("GET /v1/play/campaigns/{id}/encounters/{enc_id}/turn", getPlayCampaignEncounterTurn)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/encounters/{enc_id}/turn/advance", advancePlayCampaignEncounterTurn)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/encounters/{enc_id}/turn/delay", delayPlayCampaignEncounterTurn)
