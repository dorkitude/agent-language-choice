	mux.HandleFunc("POST /v1/play/campaigns/{id}/characters/{char_id}/transfer", transferPlayCampaignCharacter)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/characters/{char_id}/build", buildPlayCampaignCharacter)
	mux.HandleFunc("POST /v1/play/campaigns/{id}/characters/{char_id}/level-up", levelUpPlayCampaignCharacter)
